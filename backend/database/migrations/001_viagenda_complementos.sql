-- Complementos necessários ao front-end (autenticação, histórico de contato e origem da oportunidade).
-- Execute uma única vez no SQL Editor do Supabase, após conferir backup.

CREATE TABLE IF NOT EXISTS public.vendedor (
  id_vendedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome varchar NOT NULL,
  email varchar NOT NULL UNIQUE,
  senha_hash varchar NOT NULL,
  perfil varchar NOT NULL DEFAULT 'vendedor' CHECK (perfil IN ('admin','vendedor')),
  ativo boolean NOT NULL DEFAULT true,
  ultimo_login timestamp without time zone
);

ALTER TABLE public.oportunidade
  ADD COLUMN IF NOT EXISTS tipo_origem varchar,
  ADD COLUMN IF NOT EXISTS descricao varchar,
  ADD COLUMN IF NOT EXISTS data_proximo_contato date;

ALTER TABLE public.oportunidade
  DROP CONSTRAINT IF EXISTS oportunidade_tipo_origem_check;
ALTER TABLE public.oportunidade
  ADD CONSTRAINT oportunidade_tipo_origem_check
  CHECK (tipo_origem IS NULL OR tipo_origem IN ('pos_viagem','fim_pagamento','manual'));

CREATE TABLE IF NOT EXISTS public.contato (
  id_contato integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente integer NOT NULL REFERENCES public.cliente(id_cliente),
  id_oportunidade integer REFERENCES public.oportunidade(id_oportunidade),
  id_vendedor integer REFERENCES public.vendedor(id_vendedor),
  canal varchar NOT NULL CHECK (canal IN ('WhatsApp','Telefone','E-mail','Presencial')),
  mensagem varchar NOT NULL,
  resultado varchar,
  data_contato timestamp without time zone NOT NULL DEFAULT now()
);

-- Impede que execuções repetidas do cron dupliquem o mesmo ciclo.
CREATE UNIQUE INDEX IF NOT EXISTS uq_oportunidade_pos_viagem_ciclo
  ON public.oportunidade(id_viagem_referencia, ciclo_recorrencia)
  WHERE tipo_origem = 'pos_viagem';
CREATE UNIQUE INDEX IF NOT EXISTS uq_oportunidade_fim_pagamento
  ON public.oportunidade(id_viagem_referencia)
  WHERE tipo_origem = 'fim_pagamento';
CREATE INDEX IF NOT EXISTS idx_oportunidade_status_data
  ON public.oportunidade(status_oportunidade, data_proximo_contato);
CREATE INDEX IF NOT EXISTS idx_contato_cliente_data
  ON public.contato(id_cliente, data_contato DESC);
CREATE INDEX IF NOT EXISTS idx_viagem_retorno
  ON public.viagem(data_retorno) WHERE status_viagem <> 'cancelada';
CREATE INDEX IF NOT EXISTS idx_parcela_vencimento
  ON public.parcela_pagamento(data_vencimento, status_parcela);
